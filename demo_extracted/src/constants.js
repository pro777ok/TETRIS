'use strict';

// 回転状態の並び (時計回り順)
const ROTATIONS = ['0', 'R', '2', 'L'];

function cwOf(rot) {
  return ROTATIONS[(ROTATIONS.indexOf(rot) + 1) % 4];
}
function ccwOf(rot) {
  return ROTATIONS[(ROTATIONS.indexOf(rot) + 3) % 4];
}
// 180°回転で移る先の回転状態 (0<->2, R<->L)
function oppositeOf(rot) {
  return ROTATIONS[(ROTATIONS.indexOf(rot) + 2) % 4];
}

