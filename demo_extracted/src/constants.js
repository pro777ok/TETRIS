// Oミノはキック不要 (常に(0,0)のみ)
const O_KICKS = {
  '0>R': [[0,0]], 'R>0': [[0,0]], 'R>2': [[0,0]], '2>R': [[0,0]],
  '2>L': [[0,0]], 'L>2': [[0,0]], 'L>0': [[0,0]], '0>L': [[0,0]],
};

// 180°回転はキック無し(その場(0,0)でのみ回転可能)。
// ガイドラインには180°キックの定義が無く、TETR.IO式のテーブルを使うと挙動が
// SRS-X (要するに11種のテーブル) と混同されやすいため、全ミノ共通でキックを付けない。
const KICKLESS180 = [[0, 0]];
function getKicks180(pieceType, fromRot) {
  return KICKLESS180;
}

function getKicks(pieceType, fromRot, toRot) {
  const key = `${fromRot}>${toRot}`;
  if (pieceType === 'I') return I_KICKS[key];
  if (pieceType === 'O') return O_KICKS[key];
  return JLSTZ_KICKS[key];
}

// 出現位置 (盤面幅10を想定、左上基準のオフセット)
function spawnX(pieceType, boardWidth) {
  const w = SHAPES[pieceType]['0'][0].length;
  return Math.floor((boardWidth - w) / 2);
}

